use std::collections::hash_map::RandomState;
use std::hash::{BuildHasher, Hasher};
use std::path::{Path, PathBuf};

/// Keys bundled into release builds: (secret name, environment variable). Read from the environment or from the
/// git-ignored `src-tauri/.env`; builds without them (e.g. from the public source) ship no built-in key.
const BUNDLED: &[(&str, &str)] = &[("freesound", "ALCOR_FREESOUND_KEY")];

fn main() {
    tauri_build::build();
    write_builtin_keys();
}

fn write_builtin_keys() {
    let env_file = PathBuf::from(".env");
    // Watching a missing file would rerun this script on every build; after creating `.env`, touch build.rs once.
    if env_file.exists() {
        println!("cargo:rerun-if-changed=.env");
    }
    println!("cargo:rerun-if-changed=build.rs");
    let file_vars = read_env_file(&env_file);

    let mut out = String::from("// Generated by build.rs. Each key is XORed with a pad drawn fresh for every build.\n");
    out.push_str("pub const BUNDLED: &[(&str, &[u8], &[u8])] = &[\n");
    for (name, var) in BUNDLED {
        println!("cargo:rerun-if-env-changed={var}");
        let value = std::env::var(var)
            .ok()
            .or_else(|| file_vars.iter().find(|(k, _)| k == var).map(|(_, v)| v.clone()))
            .map(|v| v.trim().to_string())
            .filter(|v| !v.is_empty());
        let Some(value) = value else { continue };
        let pad = random_bytes(value.len());
        let masked: Vec<u8> = value.bytes().zip(&pad).map(|(b, p)| b ^ p).collect();
        out.push_str(&format!("    ({name:?}, &{masked:?}, &{pad:?}),\n"));
    }
    out.push_str("];\n");

    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("builtin_keys.rs");
    std::fs::write(dest, out).expect("write builtin_keys.rs");
}

/// `KEY=value` lines; blank lines and `#` comments are skipped, surrounding quotes are dropped.
fn read_env_file(path: &Path) -> Vec<(String, String)> {
    let Ok(text) = std::fs::read_to_string(path) else { return Vec::new() };
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .filter_map(|l| l.split_once('='))
        .map(|(k, v)| (k.trim().to_string(), v.trim().trim_matches('"').trim_matches('\'').to_string()))
        .collect()
}

/// `RandomState` is seeded from the OS, so this needs no extra build dependency.
fn random_bytes(len: usize) -> Vec<u8> {
    let state = RandomState::new();
    (0..len)
        .map(|i| {
            let mut h = state.build_hasher();
            h.write_usize(i);
            (h.finish() >> 24) as u8
        })
        .collect()
}
